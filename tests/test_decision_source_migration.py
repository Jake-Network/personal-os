"""An additive answer reference must preserve decisions and append-only reviews."""
from alembic import command
from sqlalchemy import create_engine, event, text
from app.modules.database.migration_manager import alembic_config


def test_source_message_upgrade_preserves_history_and_set_null(tmp_path):
    url = f"sqlite:///{tmp_path / 'decisions.db'}"
    command.upgrade(alembic_config(url), '0014_calendar_all_day')
    engine = create_engine(url)

    @event.listens_for(engine, 'connect')
    def enable_foreign_keys(connection, _):
        connection.execute('PRAGMA foreign_keys=ON')

    with engine.begin() as connection:
        connection.execute(text("INSERT INTO advisor_conversations (id,title,created_at,updated_at) VALUES (1,'질문','2026-10-01','2026-10-01')"))
        connection.execute(text("INSERT INTO advisor_messages (id,conversation_id,role,content,status,created_at) VALUES (1,1,'assistant','답변','complete','2026-10-01')"))
        connection.execute(text("INSERT INTO decision_journal (id,title,choice,rationale,alternatives,decided_at,conversation_id) VALUES (1,'결정','선택','이유','[]','2026-10-01',1)"))
        connection.execute(text("INSERT INTO decision_reviews (id,decision_id,actual_outcome,reviewed_at) VALUES (1,1,'보존할 결과','2026-10-02')"))
    with engine.begin() as connection:
        config = alembic_config(url)
        config.attributes['connection'] = connection
        command.upgrade(config, 'head')
        assert connection.execute(text('SELECT source_message_id FROM decision_journal')).scalar() is None
        assert connection.execute(text('SELECT actual_outcome FROM decision_reviews')).scalar() == '보존할 결과'
        connection.execute(text('UPDATE decision_journal SET source_message_id=1 WHERE id=1'))
        connection.execute(text('DELETE FROM advisor_messages WHERE id=1'))
        assert connection.execute(text('SELECT source_message_id FROM decision_journal')).scalar() is None
        assert connection.execute(text('SELECT choice FROM decision_journal')).scalar() == '선택'
        assert connection.execute(text('SELECT count(*) FROM decision_reviews')).scalar() == 1
        assert any(fk[3] == 'source_message_id' and fk[6] == 'SET NULL'
                   for fk in connection.execute(text('PRAGMA foreign_key_list(decision_journal)')))
    engine.dispose()


def test_head_has_no_foreign_key_drift_and_detects_real_drift(tmp_path):
    import pytest
    from alembic.util.exc import AutogenerateDiffsDetected
    url = f"sqlite:///{tmp_path / 'schema-check.db'}"
    config = alembic_config(url)
    command.upgrade(config, 'head')
    command.check(config)
    # The comparison must still reject an actually changed action, not merely
    # suppress the inline foreign key because SQLite reflection is incomplete.
    engine = create_engine(url)
    with engine.begin() as connection:
        connection.execute(text('ALTER TABLE decision_journal DROP COLUMN source_message_id'))
        connection.execute(text('ALTER TABLE decision_journal ADD COLUMN source_message_id INTEGER REFERENCES advisor_messages(id) ON DELETE CASCADE'))
    with pytest.raises(AutogenerateDiffsDetected):
        command.check(config)
    engine.dispose()
